"""
G-code Generator module for 3D Printer Filament Dryer
Supports Ender 3 and standard Marlin / Klipper / RepRap heatbeds.
"""

from typing import Dict, Any


def generate_dryer_gcode(
    temperature: int = 60,
    duration_hours: int = 8,
    duration_minutes: int = 0,
    beep_enabled: bool = True,
    beep_seconds: int = 5,
    beep_freq: int = 1000,
    beep_sequence: list = None,  # List of {freq, ms} dicts for melody mode
    beep_preset_name: str = "",  # Display name of the preset
    park_toolhead: bool = False,
    park_x: int = 10,
    park_y: int = 200,
    park_z: int = 60,
    fan_circulation: bool = False,
    fan_speed_pct: int = 20,
    disable_steppers: bool = True,
    cooldown_warning: bool = True,
    notes: str = ""
) -> Dict[str, Any]:
    """
    Generates G-code string and metadata based on parameters.
    beep_sequence: list of dicts [{freq: Hz, ms: duration}]. freq=0 means a rest/pause (G4).
    """
    # Safety sanitization
    temp = max(30, min(int(temperature), 125))
    hours = max(0, int(duration_hours))
    minutes = max(0, min(59, int(duration_minutes)))
    if hours == 0 and minutes == 0:
        minutes = 30  # minimum default fallback

    total_seconds = (hours * 3600) + (minutes * 60)
    duration_ms = total_seconds * 1000
    beep_ms = max(1, int(beep_seconds)) * 1000
    fan_pwm = max(0, min(255, int(round((fan_speed_pct / 100.0) * 255))))

    # Human readable duration
    dur_str_parts = []
    if hours > 0:
        dur_str_parts.append(f"{hours}h")
    if minutes > 0 or hours == 0:
        dur_str_parts.append(f"{minutes}m")
    duration_label = " ".join(dur_str_parts)

    filename = f"filament_dryer_{hours}h_{minutes}m_{temp}C.gcode"

    lines = []
    lines.append("; ========================================================")
    lines.append("; ♨️ 3D PRINTER FILAMENT DRYER G-CODE")
    lines.append(f"; Target Temperature : {temp}°C (Heatbed)")
    lines.append(f"; Drying Duration    : {duration_label} ({total_seconds:,} seconds / {duration_ms:,} ms)")
    if notes:
        lines.append(f"; Material / Notes   : {notes}")
    lines.append(f"; Generated by       : Filament Dryer Web Generator")
    lines.append("; ========================================================")
    lines.append("")
    lines.append("; --- Safety & Initial Setup ---")
    lines.append("; NOTE: User sudah memposisikan extruder secara manual sebelum menjalankan file ini.")
    lines.append("; Spool filament sudah diletakkan di atas bed dan ditutup kardus bersirkulasi.")
    lines.append("M220 S100               ; Reset speed multiplier to 100%")
    lines.append("M221 S100               ; Reset flow rate to 100%")
    lines.append("M104 S0                 ; Pastikan heater nozzle MATI (keamanan)")
    lines.append("M84                     ; Bebaskan semua motor stepper — nozzle bisa digeser bebas")
    lines.append("")

    if park_toolhead:
        lines.append("; --- [OPSIONAL] Parkir Nozzle via G-code ---")
        lines.append("; PERINGATAN: Pastikan tidak ada spool/kardus di atas bed sebelum homing!")
        lines.append("G28                     ; Home all axes")
        lines.append(f"G1 Z{park_z} F1500           ; Lift nozzle ({park_z}mm)")
        lines.append(f"G1 X{park_x} Y{park_y} F3000         ; Parkir ke sudut (X{park_x} Y{park_y})")
        lines.append("")

    if fan_circulation and fan_pwm > 0:
        lines.append("; --- Air Circulation Fan ---")
        lines.append(f"M106 S{fan_pwm}                 ; Turn on fan at {fan_speed_pct}% to circulate warm air")
        lines.append("")

    lines.append("; --- Heatbed Warming Phase ---")
    lines.append(f"M117 Heating bed to {temp}C ; LCD status message")
    lines.append(f"M140 S{temp}               ; Set heatbed target temperature")
    lines.append(f"M190 S{temp}               ; Wait until bed reaches {temp}°C")
    lines.append("")

    lines.append("; --- Drying Phase (Timer starts after bed is hot) ---")
    lines.append(f"M117 Drying {duration_label}...      ; LCD status message")
    lines.append(f"G4 P{duration_ms}         ; Dwell / pause for {duration_label}")
    lines.append("")

    lines.append("; --- Drying Complete & Cooldown Phase ---")
    lines.append("M117 Drying Complete!    ; LCD status message")
    lines.append("M140 S0                 ; Turn OFF heatbed")

    if fan_circulation:
        lines.append("M107                    ; Turn OFF fan")

    if beep_enabled:
        # ----- MELODY / SEQUENCE MODE -----
        if beep_sequence and len(beep_sequence) > 0:
            preset_label = beep_preset_name if beep_preset_name else "Custom Sequence"
            lines.append(f"; Audible completion melody: {preset_label}")
            for i, note in enumerate(beep_sequence):
                try:
                    freq = int(note.get("freq", 1000))
                    ms = int(note.get("ms", 200))
                    if ms <= 0:
                        continue
                    if freq <= 0:
                        # Silence / rest between notes
                        lines.append(f"G4 P{ms}                 ; Pause/rest {ms}ms")
                    else:
                        lines.append(f"M300 S{freq} P{ms}         ; Note {i + 1}: {freq}Hz for {ms}ms")
                except (TypeError, ValueError):
                    continue
        # ----- SIMPLE CUSTOM BEEP MODE -----
        else:
            lines.append(f"; Audible completion alert: {beep_seconds}s at {beep_freq}Hz")
            lines.append(f"M300 S{beep_freq} P{beep_ms}     ; Beep alert")

    if disable_steppers:
        lines.append("M84                     ; Disable all stepper motors (cool down motors)")

    lines.append("")
    lines.append("; ========================================================")
    lines.append("; PROCESS FINISHED. Filament is dried and ready to store.")
    lines.append("; ========================================================")


    gcode_content = "\n".join(lines) + "\n"

    return {
        "filename": filename,
        "gcode": gcode_content,
        "temperature": temp,
        "duration_hours": hours,
        "duration_minutes": minutes,
        "total_seconds": total_seconds,
        "duration_ms": duration_ms,
        "duration_label": duration_label,
    }
